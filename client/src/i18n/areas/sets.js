import { CODE_SETS, GENERATED_DECADES, GENERATED_GENRES, generatedId, generatedTitles } from '@shared/sets.js';

const N = ' ';

/** Noms des cadres des coffrets (« Coffret · Les classiques du bac ») : un par coffret du code et par genre × décennie. */
function frameNames(lang, prefix) {
  const out = {};
  for (const s of CODE_SETS) out[`set-${s.id}`] = `${prefix} · ${s.title[lang]}`;
  for (const g of GENERATED_GENRES) {
    for (const d of GENERATED_DECADES) out[`set-${generatedId(g, d)}`] = `${prefix} · ${generatedTitles(g, d)[lang]}`;
  }
  return out;
}

